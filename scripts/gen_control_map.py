"""Generate pylib/delugemu/_controls.py from the C front-panel headers.

The emulator's named-control geometry (button/encoder centres, pad grid layout,
skin dimensions) is defined once in C and consumed by the device models. The
Python scripting interface needs the same geometry to resolve a control name to
the pixel coordinates it clicks over QMP. Rather than hand-maintain a parallel
table that would silently drift, we parse the C headers and emit a committed
Python module. `tests/geometry-sync.sh` re-runs this and fails if the committed
output is stale.

Sources:
  src/include/hw/display/deluge_skin_controls.h  -- deluge_skin_controls[] +
                                                    DELUGE_MASTER_VOL_*
  src/include/hw/display/deluge_skin_layout.h     -- image size + pad geometry
"""
import os
import re
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CONTROLS_H = os.path.join(REPO, "src/include/hw/display/deluge_skin_controls.h")
LAYOUT_H = os.path.join(REPO, "src/include/hw/display/deluge_skin_layout.h")
OUT = os.path.join(REPO, "pylib/delugemu/_controls.py")

# A row of deluge_skin_controls[]: { "NAME", col, row, cx, cy, radius, has_led, ...
ROW_RE = re.compile(
    r'\{\s*"([A-Z0-9_]+)"\s*,\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*,'
    r'\s*(\d+)\s*,\s*(true|false)'
)
DEFINE_RE = re.compile(r'#define\s+([A-Z0-9_]+)\s+(\d+)')


def read(path):
    with open(path, encoding="utf-8") as fh:
        return fh.read()


def parse_defines(text):
    return {m.group(1): int(m.group(2)) for m in DEFINE_RE.finditer(text)}


def parse_controls(text):
    controls = {}
    for m in ROW_RE.finditer(text):
        name, col, row, cx, cy, radius, has_led = m.groups()
        controls[name] = {
            "col": int(col),
            "row": int(row),
            "cx": int(cx),
            "cy": int(cy),
            "radius": int(radius),
            "has_led": has_led == "true",
        }
    return controls


def build():
    controls_txt = read(CONTROLS_H)
    layout = parse_defines(read(LAYOUT_H))
    defs = parse_defines(controls_txt)
    controls = parse_controls(controls_txt)
    if not controls:
        raise SystemExit("no controls parsed from %s" % CONTROLS_H)

    data = {
        "image_width": layout["DELUGE_SKIN_IMAGE_WIDTH"],
        "image_height": layout["DELUGE_SKIN_IMAGE_HEIGHT"],
        "controls": controls,
        "pad": {
            "main_x0": layout["DELUGE_SKIN_PAD_MAIN_X0"],
            "main_dx": layout["DELUGE_SKIN_PAD_MAIN_DX"],
            "side_x0": layout["DELUGE_SKIN_PAD_SIDE_X0"],
            "side_dx": layout["DELUGE_SKIN_PAD_SIDE_DX"],
            "side_y0": layout["DELUGE_SKIN_PAD_SIDE_Y0"],
            "side_dy": layout["DELUGE_SKIN_PAD_SIDE_DY"],
            "rows": 8,
            "main_cols": 16,
            "side_cols": 2,
        },
        "master_vol": {
            "cx": defs["DELUGE_MASTER_VOL_CX"],
            "cy": defs["DELUGE_MASTER_VOL_CY"],
            "radius": defs["DELUGE_MASTER_VOL_R"],
        },
    }
    return data


def render(data):
    lines = [
        "# SPDX-License-Identifier: GPL-2.0-or-later",
        "# AUTO-GENERATED by scripts/gen_control_map.py from the C headers.",
        "# Do not edit by hand; run the generator and commit the result.",
        "import enum",
        "",
        "IMAGE_WIDTH = %d" % data["image_width"],
        "IMAGE_HEIGHT = %d" % data["image_height"],
        "",
        "# name -> {col, row, cx, cy, radius, has_led}. An encoder (turnable) is",
        "# exactly a control with has_led == False.",
        "CONTROLS = {",
    ]
    for name in sorted(data["controls"]):
        c = data["controls"][name]
        lines.append(
            '    "%s": {"col": %d, "row": %d, "cx": %d, "cy": %d, '
            '"radius": %d, "has_led": %s},'
            % (name, c["col"], c["row"], c["cx"], c["cy"], c["radius"],
               c["has_led"])
        )
    lines.append("}")
    lines.append("")
    lines.append("PAD = %r" % (data["pad"],))
    lines.append("")
    lines.append("MASTER_VOL = %r" % (data["master_vol"],))
    lines.append("")
    lines.append("")
    # The master OUTPUT LEVEL knob is not a row in deluge_skin_controls[] (it
    # has no col/row/LED), but it is a named, clickable control, so it gets an
    # enum member alongside the table rows.
    enum_names = sorted(set(data["controls"]) | {"MASTER_VOL"})
    lines.append("class Control(enum.Enum):")
    lines.append('    """Every named front-panel control.')
    lines.append("")
    lines.append("    The canonical upper-case name is the member value, so a")
    lines.append("    scenario/CLI string and ``Control.<NAME>`` resolve alike.")
    lines.append('    """')
    for name in enum_names:
        lines.append('    %s = "%s"' % (name, name))
    lines.append("")
    return "\n".join(lines)


def main():
    text = render(build())
    if "--check" in sys.argv:
        try:
            current = read(OUT)
        except FileNotFoundError:
            current = None
        if current != text:
            sys.stderr.write(
                "pylib/delugemu/_controls.py is out of date; "
                "run scripts/gen_control_map.py\n")
            return 1
        print("control map up to date")
        return 0
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write(text)
    print("wrote %s (%d controls)" % (OUT, len(build()["controls"])))
    return 0


if __name__ == "__main__":
    sys.exit(main())
